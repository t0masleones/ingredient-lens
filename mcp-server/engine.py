HEADER = re.compile(r"\b(ingredientes|ingredients|ingr[eé]dients|zutaten|ingredienti|ingredi[eë]nten)\s*:", re.I)
# Allergen statements end the list wherever they start; claims only when they stand alone ("Oats, sugar. VEGAN"),
# so "vegan butter" or "queijo vegano" stay ingredients.
STATEMENT_START = re.compile(
    r"\b(alergicos|alergenos|allergens|allergenes|allergene|contem|contains|contiene|contient|enthalt|bevat|"
    r"pode conter|may also contain|may contain|puede contener|peut aussi contenir|peut egalement contenir|"
    r"peut contenir|kann spuren|puo contenere|kan sporen|traces eventuelles|traces possibles|nao contem)\b")
CLAIM_START = re.compile(
    r"(?:^|[\n,;])\s*(zero lactose|sem lactose|lactose free|gluten free|sem gluten|sin gluten|vegano|vegana|vegan)"
    r"\s*(?=$|[\n,;.!])")
# "contains 2% or less of:", "contém menos de 2% de:" introduce more ingredients, not a statement; so does
# "Vegetable oil contains one or more of the following: corn, soybean..." (alternatives, not allergens).
MINOR_INGREDIENTS = re.compile(
    r"\b(?:(?:contains|cont[eé]m|contiene)\s+)?(?:\d+(?:[.,]\d+)?\s*%\s+or\s+less\s+of|less\s+than\s+\d+(?:[.,]\d+)?\s*%\s+of|"
    r"menos\s+de\s+\d+(?:[.,]\d+)?\s*%\s+de)\s*:?|"
    r"\b(?:and/or\s+)?contains?\s+one\s+or\s+more\s+of(?:\s+the\s+following)?(?:\s+(?:vegetable\s+)?(?:oils?|fats?))?\s*:?",
    re.I)
# An allergen header ends the list even inside parentheses: OCR text often loses a closing parenthesis.
ALLERGEN_HEADER = re.compile(r"(alergicos|alergenos|allergens|allergenes|allergene)\b")
# Innermost parentheses or brackets, for statements printed inside an ingredient: "chocolate (pode conter leite)".
INNER_PARENS = re.compile(r"[(\[]([^()\[\]]*)[)\]]")
# Claim words that can open a label before the list. Only the claim itself is matched ("sem glúten", "rico em
# fibras"), never the words after it, so "SEM GLÚTEN Leite integral" keeps "Leite integral" as an ingredient.
_FREE_FROM = (r"(?:sem|zero|sans|ohne|senza)\s+\S+|(?:livre de|isento de|rico em|fonte de|free from|high in|"
              r"source of|no added|naturally)\s+\S+|\S+ free")
# A diet word only counts as a leading claim when punctuation follows it: "Vegan, sugar..." but not "vegan butter".
LEADING_CLAIM = re.compile(rf"\s*(?:(?:contem fenilalanina|contains phenylalanine|{_FREE_FROM})(?:\s*[,;.\n]|\s+|$)|"
                           r"(?:vegano|vegana|vegan|vegetariano|vegetariana|vegetarian)\s*(?:[,;.\n]|$))")
# A whole item that is only a claim; "fat free milk" is milk and stays an ingredient.
FREE_FROM_ITEM = re.compile(rf"^(?:{_FREE_FROM}|contem fenilalanina|contains phenylalanine)$")
PERCENT = re.compile(r"^\s*\d+(?:[.,]\d+)?\s*%\s*$")
ADDITIVE_CODE = re.compile(r"^\s*(?:ins|e)\s*-?\s*\d{3,4}[a-z]?(?:\s*[ivx]+)?\s*$", re.I)
GLUTEN_FREE = re.compile(r"\b(nao contem gluten|sem gluten|isento de gluten|gluten free|sin gluten|libre de gluten|"
                         r"sans gluten|glutenfrei|senza glutine|glutenvrij)\b")
GLUTEN_CONTAINS = re.compile(r"\b(contem gluten|contains gluten|contiene gluten)\b")
LACTOSE_FREE = re.compile(r"(\bzero lactose|\bsem lactose|\bisento de lactose|0% lactose|\bnao contem lactose|"
                          r"\blactose free|\bsin lactosa)\b")
LACTOSE_CONTAINS = re.compile(r"\b(contem lactose|contains lactose|contiene lactosa)\b")
VEGAN_CLAIM = re.compile(r"\b(vegano|vegana|vegan|100% vegetal|plant based)\b")
VEGETARIAN_CLAIM = re.compile(r"\b(vegetariano|vegetariana|vegetarian)\b")
# "May contain" in the 7 label languages, including trace wording ("Traces éventuelles de lait", "Spuren von").
_MAY = (r"pode conter|may also contain|may contain|puede contener|peut aussi contenir|peut egalement contenir|"
        r"peut contenir|kann spuren|spuren von|puo contenere|kan sporen|traces? (?:eventuelles? |possibles? )?d(?:e|es|u)?|"
        r"tracce di|trazas de|tracos de")
MAY_CONTAIN = re.compile(rf"\b({_MAY})\b")
CONTAINS = re.compile(r"\b(contem|contains|contiene|contient|enthalt|bevat)\b")


def paren_depths(text: str) -> list[int]:
    """Parenthesis depth at each character, counting only pairs that close. OCR text often loses a closing
    parenthesis ("farinha de trigo (enriquecida com ferro, açúcar..."); an unclosed one is read as a character, so
    it cannot hide the rest of the label inside an ingredient."""
    stack, pairs = [], []
    for i, ch in enumerate(text):
        if ch in "([":
            stack.append(i)
        elif ch in ")]" and stack:
            pairs.append((stack.pop(), i))
    delta = [0] * (len(text) + 1)
    for start, end in pairs:
        delta[start + 1] += 1
        delta[end] -= 1
    depths, depth = [], 0
    for i in range(len(text)):
        depth += delta[i]
        depths.append(depth)
    return depths


def split_top_level(text: str) -> list[str]:
    """Split on commas/semicolons/newlines that are not inside parentheses or a decimal ("12,5%")."""
    parts, buf = [], []
    depths = paren_depths(text)
    for i, ch in enumerate(text):
        depth = depths[i]
        decimal = ch == "," and 0 < i < len(text) - 1 and text[i - 1].isdigit() and text[i + 1].isdigit()
        if depth == 0 and ch in ",;\n" and not decimal:
            parts.append("".join(buf))
            buf = []
        else:
            buf.append(ch)
    parts.append("".join(buf))
    return [p.strip(" .") for p in parts if p.strip(" .")]


def split_ingredients(list_text: str) -> list[str]:
    """Flatten 'A, B (b1, b2), C' into ['A', 'B', 'b1', 'b2', 'C']."""
    out = []
    for item in split_top_level(list_text):
        m = re.match(r"^(.*?)\((.*)\)\s*(.*)$", item, re.S)
        if m:
            head, inner = f"{m.group(1)} {m.group(3)}".strip(), m.group(2)
            # "(65%)" is a quantity and "(INS 322)" names the head; neither is a separate ingredient.
            if PERCENT.match(inner):
                inner = ""
            elif ADDITIVE_CODE.match(inner):
                head, inner = f"{head} {inner.strip()}".strip(), ""
            if head:
                out.append(head)
            if inner:
                out.extend(split_ingredients(inner))
        else:
            out.append(item)
    return out


@dataclass
class Statements:
    allergen_statement_found: bool = False
    contains: set[str] = field(default_factory=set)
    may_contain: set[str] = field(default_factory=set)
    gluten: str = "not found"       # "contains", "free", "not found"
    lactose: str = "not found"      # "contains", "free", "not found"
    vegan_claim: bool = False
    vegetarian_claim: bool = False
    raw: str = ""


def parse_label(text: str, matcher: Matcher) -> tuple[list[str], Statements]:
    """Return (ingredient items, statements). Recipes without a header are all ingredients."""
    text = MINOR_INGREDIENTS.sub(",", text)
    header = HEADER.search(text)
    if header:
        body = text[header.end():]
        # Claims and warnings printed before the list ("Sem glúten, Rico em fibras, Farinha de trigo...",
        # "CONTÉM FENILALANINA Água...") are statements; only the claim words are moved, never what follows.
        leading = []
        while m := LEADING_CLAIM.match(normalize_keep_len(body)):
            leading.append(body[:m.end()].strip(" ,;."))
            body = body[m.end():]
        norm = normalize_keep_len(body)
        # The list ends at the first statement, standalone claim or sentence end, whichever comes first.
        sentence_end, list_periods = _list_sentence_end(body)
        ends = [m.start(m.lastindex or 0) for m in (_first_top_level_statement(norm), CLAIM_START.search(norm)) if m]
        cut = min(ends + [sentence_end])
        list_text = "".join("," if i in list_periods else ch for i, ch in enumerate(body[:cut]))
        rest = ". ".join([text[:header.start()]] + leading + [body[cut:]])
    else:
        # A recipe such as "Pastry for vegan guests: flour; lard; salt" -> drop the title.
        title = re.match(r"^[^:;\n]{0,100}:\s*", text)
        list_text = text[title.end():] if title else text
        # No header: only an allergen statement ends the list (recipes use "1 tsp. salt", so not periods).
        stmt = _first_top_level_statement(normalize_keep_len(list_text))
        list_text, rest = (list_text[:stmt.start()], list_text[stmt.start():]) if stmt else (list_text, "")
    list_text, inline = _inline_statements(list_text)
    # Free-from and nutrition claims inside the list ("Feijão, sem conservantes") are statements, not ingredients.
    items, claims = [], []
    for item in split_ingredients(list_text):
        (claims if FREE_FROM_ITEM.match(normalize(item)) else items).append(item)
    return items, parse_statements(". ".join([rest] + claims), matcher, inline)


def _first_top_level_statement(norm: str) -> re.Match | None:
    """The first statement that is not inside an ingredient's parentheses.

    "arôme naturel (contient alcool)", "vinagre (contém sulfitos)" and "coconut flakes (contains: sulfur dioxide)"
    describe one ingredient. Ending the list there dropped every ingredient after it (gelatin came out 🟢 for a
    vegan) and read the rest of the list as the label's allergen statement (found by the v0.6 benchmark).
    """
    depths = paren_depths(norm)
    for m in STATEMENT_START.finditer(norm):
        if ALLERGEN_HEADER.match(norm, m.start()):
            return m
        # "(CONTÉM ÓLEO DE SOJA, ÁGUA, … SORO DE LEITE" whose ")" was lost is still an ingredient's note.
        if depths[m.start()] == 0 and not norm[:m.start()].rstrip().endswith(("(", "[")):
            return m
    return None


def _inline_statements(list_text: str) -> tuple[str, list[str]]:
    """Statements printed inside an ingredient's parentheses.

    "(pode conter leite)" is a may-contain statement, not an ingredient, so it leaves the list. "(contém leite e
    soja)" names what the ingredient contains: the words stay as sub-ingredients and only the verb goes, so the item
    cannot start a statement if the list is written out again. "(contém glúten)" is also read as the gluten
    statement. None of them is the label's allergen statement, so none starts the completeness check (XC2) or
    settles the declaration rows of the checklist.
    """
    inline = []

    def take(m: re.Match) -> str:
        inner, norm = m.group(1), normalize_keep_len(m.group(1))
        may = MAY_CONTAIN.search(norm)
        if may:
            inline.append(inner[may.start():])
            keep = inner[:may.start()].strip(" ,;:")
            return f"({keep})" if keep else ""
        if GLUTEN_CONTAINS.search(norm) or LACTOSE_CONTAINS.search(norm):
            inline.append(inner)
        has = CONTAINS.search(norm)
        if has:
            inner = (inner[:has.start()] + inner[has.end():].lstrip(" :")).strip(" ,;")
            return f"({inner})" if inner else ""
        return m.group(0)
    return INNER_PARENS.sub(take, list_text), inline


def _list_sentence_end(body: str) -> tuple[int, set[int]]:
    """Where the ingredient list ends at a period, and which periods are only separators inside it.

    Real labels put periods inside lists ("HASELNÜSSE (13%). MAGERMILCHPULVER (8,7%), Kakao",
    "MILK CHOCOLATE (SUGAR, MILK. CHOCOLATE..."). A period inside parentheses never ends the list; a period
    followed by more comma-separated items is read as a separator. Dropping those items would hide allergens.
    """
    depths, separators = paren_depths(body), set()
    for i, ch in enumerate(body):
        if ch == "." and depths[i] == 0 and (i + 1 == len(body) or body[i + 1].isspace()):
            following = re.split(r"\.(?:\s|$)", body[i + 1:], maxsplit=1)[0]
            if "," in following or ";" in following:
                separators.add(i)
            else:
                return i, separators
    return len(body), separators


def normalize_keep_len(text: str) -> str:
    """Accent-strip and lowercase one character at a time, keeping offsets aligned."""
    out = []
    for ch in text:
        base = "".join(c for c in unicodedata.normalize("NFKD", ch) if not unicodedata.combining(c))
        out.append((base or ch)[0].lower())
    return "".join(out)


def groups_in(text: str, matcher: Matcher) -> set[str]:
    groups = set()
    for t in matcher.find(text):
        groups |= t.allergens & ALLERGEN_GROUPS
    return groups


def parse_statements(text: str, matcher: Matcher, inline: list[str] | tuple = ()) -> Statements:
    """Label statements from the text after the list, plus statements printed inside an ingredient's parentheses
    (`inline`), which add what they say but never count as the label's allergen statement."""
    st = Statements(raw=". ".join([text.strip()] + list(inline)) if inline else text.strip())
    for part in inline:
        n = normalize(part)
        if GLUTEN_CONTAINS.search(n) and not GLUTEN_FREE.search(n):
            st.gluten = "contains"
        if LACTOSE_CONTAINS.search(n):
            st.lactose = "contains"
        if may := MAY_CONTAIN.search(n):
            st.may_contain |= groups_in(n[may.end():], matcher)
    norm = normalize(text)
    if GLUTEN_FREE.search(norm):
        st.gluten = "free"
    elif GLUTEN_CONTAINS.search(norm):
        st.gluten = "contains"
    if LACTOSE_FREE.search(norm):
        st.lactose = "free"
    elif LACTOSE_CONTAINS.search(norm):
        st.lactose = "contains"
    st.vegan_claim = bool(VEGAN_CLAIM.search(norm))
    st.vegetarian_claim = bool(VEGETARIAN_CLAIM.search(norm))

    # Remove the gluten/lactose claims so "não contém glúten" is not read as an allergen.
    norm = GLUTEN_FREE.sub(" ", LACTOSE_FREE.sub(" ", LACTOSE_CONTAINS.sub(" ", norm)))
    for sentence in re.split(r"[.!]", norm):
        may = MAY_CONTAIN.search(sentence)
        head, tail = (sentence[:may.start()], sentence[may.end():]) if may else (sentence, "")
        if tail:
            st.allergen_statement_found = True
            st.may_contain |= groups_in(tail, matcher)
        has = CONTAINS.search(head)
        if has:
            if re.search(r"\b(alergicos|alergenos|allergens|allergenes|allergene|contains|contiene|contient|enthalt|"
                         r"bevat|derivados)\b", head):
                st.allergen_statement_found = True
            st.contains |= groups_in(head[has.end():], matcher)
        elif re.match(r"\s*derivados de\b", head):
            # "CONTÉM GLÚTEN. DERIVADOS DE SOJA": the RDC 26/2015 form split by a period (common in OCR text).
            st.allergen_statement_found = True
            st.contains |= groups_in(head, matcher)
    return st


# ---------------------------------------------------------------- checking

def normalize_avoid(avoid: list[str]) -> list[str]:
    out = []
    for a in avoid:
        a = normalize(a).replace("-", " ")
        a = AVOID_ALIASES.get(a, a.replace(" ", "_"))
        if a not in out:
            out.append(a)
    return out


