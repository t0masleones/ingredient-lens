def normalize(text: str) -> str:
    """Lowercase, strip accents, turn hyphens into spaces, collapse whitespace."""
    text = unicodedata.normalize("NFKD", text)
    text = "".join(c for c in text if not unicodedata.combining(c)).lower().replace("ß", "ss")
    text = re.sub(r"[‐-―-]", " ", text)
    text = text.replace("_", " ")    # Open Food Facts marks allergens as _weizenmehl_
    return re.sub(r"\s+", " ", text).strip()


def worst(*levels: str) -> str:
    return max(levels, key=RANK.__getitem__, default="green")


# ---------------------------------------------------------------- database

def build_db(csv_paths: tuple[Path, ...] = (CSV_PATH, OFF_PATH), db_path: Path = DB_PATH) -> Path:
    """(Re)build the SQLite ingredient master from the versioned CSVs. Earlier files win on duplicate terms."""
    db_path.unlink(missing_ok=True)
    con = sqlite3.connect(db_path)
    con.execute("""CREATE TABLE ingredient (
        term TEXT PRIMARY KEY, lang TEXT, lactose TEXT, gluten TEXT, allergens TEXT,
        may_allergens TEXT, origin TEXT, animal_type TEXT, note TEXT, source TEXT)""")
    for i, path in enumerate(p for p in csv_paths if p.exists()):
        with open(path, encoding="utf-8", newline="") as f:
            rows = [{**r, "term": normalize(r["term"])} for r in csv.DictReader(f)]
        # The curated file must not contain duplicates; generated files only fill gaps.
        con.executemany(f"""INSERT {'OR IGNORE ' if i else ''}INTO ingredient VALUES (:term, :lang, :lactose,
            :gluten, :allergens, :may_allergens, :origin, :animal_type, :note, :source)""", rows)
    con.commit()
    con.close()
    return db_path


def connect() -> sqlite3.Connection:
    newest = max(p.stat().st_mtime for p in (CSV_PATH, OFF_PATH) if p.exists())
    if not DB_PATH.exists() or DB_PATH.stat().st_mtime < newest:
        build_db()
    con = sqlite3.connect(DB_PATH)
    con.row_factory = sqlite3.Row
    return con


@dataclass
class Term:
    term: str
    lactose: str
    gluten: str
    allergens: set[str]
    may_allergens: set[str]
    origin: str
    animal_type: str
    note: str
    source: str

    @classmethod
    def from_row(cls, r: sqlite3.Row) -> "Term":
        split = lambda s: {x for x in (s or "").split(";") if x}
        allergens = split(r["allergens"])
        if r["gluten"] == "red":
            allergens.add("gluten")
        return cls(r["term"], r["lactose"] or "", r["gluten"] or "", allergens, split(r["may_allergens"]),
                   r["origin"], r["animal_type"] or "", r["note"] or "", r["source"])


class Matcher:
    """Longest-match term finder over normalized text (allows a plural s/es)."""

    def __init__(self, con: sqlite3.Connection | None = None, sources: str = "all"):
        # Terms are loaded into memory; a connection opened here is closed so the .db file stays rebuildable.
        where = "" if sources == "all" else f" WHERE source NOT LIKE '{OFF_SOURCE}%'"
        with closing(connect()) if con is None else nullcontext(con) as c:
            self.terms = {r["term"]: Term.from_row(r) for r in c.execute(f"SELECT * FROM ingredient{where}")}
        alternation = "|".join(re.escape(t) for t in sorted(self.terms, key=len, reverse=True))
        # Plural and German case endings: "ovos", "nozes", "Haselnüssen".
        self.pattern = re.compile(rf"\b({alternation})(?:s|es|n|en)?\b")
        imported = sum(t.source.startswith(OFF_SOURCE) for t in self.terms.values())
        self.data_version = f"{len(self.terms) - imported} curated + {imported} Open Food Facts"

    def find(self, text: str) -> list[Term]:
        return [self.terms[m.group(1)] for m in self.pattern.finditer(normalize(text))]


# ---------------------------------------------------------------- parsing

HEADER = re.compile(r"\b(ingredientes|ingredients|ingr[eé]dients|zutaten|ingredienti|ingredi[eë]nten)\s*:", re.I)
# Allergen statements end the list wherever they start; claims only when they stand alone ("Oats, sugar. VEGAN"),
# so "vegan butter" or "queijo vegano" stay ingredients.
STATEMENT_START = re.compile(
    r"\b(alergicos|alergenos|allergens|allergenes|allergene|contem|contains|contiene|contient|enthalt|bevat|"
    r"pode conter|may also contain|may contain|puede contener|peut aussi contenir|peut egalement contenir|"
    r"peut contenir|kann spuren|puo contenere|kan sporen|traces eventuelles|traces possibles|nao contem)\b")
CLAIM_START = re.compile(
    r"(?:^|[\n,;])\s*(zero lactose|sem lactose|lactose free|gluten free|sem gluten|sin gluten|vegano|vegana|vegan)"
    r"\s*(?=$|[\n,;.!])")
# "contains 2% or less of:", "contém menos de 2% de:" introduce more ingredients, not a statement.
MINOR_INGREDIENTS = re.compile(
    r"\b(?:(?:contains|cont[eé]m|contiene)\s+)?(?:\d+(?:[.,]\d+)?\s*%\s+or\s+less\s+of|less\s+than\s+\d+(?:[.,]\d+)?\s*%\s+of|"
    r"menos\s+de\s+\d+(?:[.,]\d+)?\s*%\s+de)\s*:?", re.I)
# Claim words that can open a label before the list. Only the claim itself is matched ("sem glúten", "rico em
# fibras"), never the words after it, so "SEM GLÚTEN Leite integral" keeps "Leite integral" as an ingredient.
_FREE_FROM = (r"(?:sem|zero|sans|ohne|senza)\s+\S+|(?:livre de|isento de|rico em|fonte de|free from|high in|"
              r"source of|no added|naturally)\s+\S+|\S+ free")
# A diet word only counts as a leading claim when punctuation follows it: "Vegan, sugar..." but not "vegan butter".
LEADING_CLAIM = re.compile(rf"\s*(?:(?:contem fenilalanina|contains phenylalanine|{_FREE_FROM})(?:\s*[,;.\n]|\s+|$)|"
                           r"(?:vegano|vegana|vegan|vegetariano|vegetariana|vegetarian)\s*(?:[,;.\n]|$))")
# A whole item that is only a claim; "fat free milk" is milk and stays an ingredient.
FREE_FROM_ITEM = re.compile(rf"^(?:{_FREE_FROM}|contem fenilalanina|contains phenylalanine)$")
PERCENT = re.compile(r"^\s*\d+(?:[.,]\d+)?\s*%\s*$")
ADDITIVE_CODE = re.compile(r"^\s*(?:ins|e)\s*-?\s*\d{3,4}[a-z]?(?:\s*[ivx]+)?\s*$", re.I)
GLUTEN_FREE = re.compile(r"\b(nao contem gluten|sem gluten|isento de gluten|gluten free|sin gluten|libre de gluten|"
                         r"sans gluten|glutenfrei|senza glutine|glutenvrij)\b")
GLUTEN_CONTAINS = re.compile(r"\b(contem gluten|contains gluten|contiene gluten)\b")
LACTOSE_FREE = re.compile(r"(\bzero lactose|\bsem lactose|\bisento de lactose|0% lactose|\bnao contem lactose|"
                          r"\blactose free|\bsin lactosa)\b")
LACTOSE_CONTAINS = re.compile(r"\b(contem lactose|contains lactose|contiene lactosa)\b")
VEGAN_CLAIM = re.compile(r"\b(vegano|vegana|vegan|100% vegetal|plant based)\b")
VEGETARIAN_CLAIM = re.compile(r"\b(vegetariano|vegetariana|vegetarian)\b")
# "May contain" in the 7 label languages, including trace wording ("Traces éventuelles de lait", "Spuren von").
_MAY = (r"pode conter|may also contain|may contain|puede contener|peut aussi contenir|peut egalement contenir|"
        r"peut contenir|kann spuren|spuren von|puo contenere|kan sporen|traces? (?:eventuelles? |possibles? )?d(?:e|es|u)?|"
        r"tracce di|trazas de|tracos de")
MAY_CONTAIN = re.compile(rf"\b({_MAY})\b")
CONTAINS = re.compile(r"\b(contem|contains|contiene|contient|enthalt|bevat)\b")


def split_top_level(text: str) -> list[str]:
    """Split on commas/semicolons/newlines that are not inside parentheses or a decimal ("12,5%")."""
    parts, depth, buf = [], 0, []
    for i, ch in enumerate(text):
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth = max(depth - 1, 0)
        decimal = ch == "," and 0 < i < len(text) - 1 and text[i - 1].isdigit() and text[i + 1].isdigit()
        if depth == 0 and ch in ",;\n" and not decimal:
            parts.append("".join(buf))
            buf = []
        else:
            buf.append(ch)
    parts.append("".join(buf))
    return [p.strip(" .") for p in parts if p.strip(" .")]


def split_ingredients(list_text: str) -> list[str]:
    """Flatten 'A, B (b1, b2), C' into ['A', 'B', 'b1', 'b2', 'C']."""
    out = []
    for item in split_top_level(list_text):
        m = re.match(r"^(.*?)\((.*)\)\s*(.*)$", item, re.S)
        if m:
            head, inner = f"{m.group(1)} {m.group(3)}".strip(), m.group(2)
            # "(65%)" is a quantity and "(INS 322)" names the head; neither is a separate ingredient.
            if PERCENT.match(inner):
                inner = ""
            elif ADDITIVE_CODE.match(inner):
                head, inner = f"{head} {inner.strip()}".strip(), ""
            if head:
                out.append(head)
            if inner:
                out.extend(split_ingredients(inner))
        else:
            out.append(item)
    return out


@dataclass
class Statements:
    allergen_statement_found: bool = False
    contains: set[str] = field(default_factory=set)
    may_contain: set[str] = field(default_factory=set)
    gluten: str = "not found"       # "contains", "free", "not found"
    lactose: str = "not found"      # "contains", "free", "not found"
    vegan_claim: bool = False
    vegetarian_claim: bool = False
    raw: str = ""


def parse_label(text: str, matcher: Matcher) -> tuple[list[str], Statements]:
    """Return (ingredient items, statements). Recipes without a header are all ingredients."""
    text = MINOR_INGREDIENTS.sub(",", text)
    header = HEADER.search(text)
    if header:
        body = text[header.end():]
        # Claims and warnings printed before the list ("Sem glúten, Rico em fibras, Farinha de trigo...",
        # "CONTÉM FENILALANINA Água...") are statements; only the claim words are moved, never what follows.
        leading = []
        while m := LEADING_CLAIM.match(normalize_keep_len(body)):
            leading.append(body[:m.end()].strip(" ,;."))
            body = body[m.end():]
        norm = normalize_keep_len(body)
        # The list ends at the first statement, standalone claim or sentence end, whichever comes first.
        sentence_end, list_periods = _list_sentence_end(body)
        ends = [m.start(m.lastindex or 0) for m in (STATEMENT_START.search(norm), CLAIM_START.search(norm)) if m]
        cut = min(ends + [sentence_end])
        list_text = "".join("," if i in list_periods else ch for i, ch in enumerate(body[:cut]))
        rest = ". ".join([text[:header.start()]] + leading + [body[cut:]])
    else:
        # A recipe such as "Pastry for vegan guests: flour; lard; salt" -> drop the title.
        title = re.match(r"^[^:;\n]{0,100}:\s*", text)
        list_text = text[title.end():] if title else text
        # No header: only an allergen statement ends the list (recipes use "1 tsp. salt", so not periods).
        stmt = STATEMENT_START.search(normalize_keep_len(list_text))
        list_text, rest = (list_text[:stmt.start()], list_text[stmt.start():]) if stmt else (list_text, "")
    # Free-from and nutrition claims inside the list ("Feijão, sem conservantes") are statements, not ingredients.
    items, claims = [], []
    for item in split_ingredients(list_text):
        (claims if FREE_FROM_ITEM.match(normalize(item)) else items).append(item)
    return items, parse_statements(". ".join([rest] + claims), matcher)


def _list_sentence_end(body: str) -> tuple[int, set[int]]:
    """Where the ingredient list ends at a period, and which periods are only separators inside it.

    Real labels put periods inside lists ("HASELNÜSSE (13%). MAGERMILCHPULVER (8,7%), Kakao",
    "MILK CHOCOLATE (SUGAR, MILK. CHOCOLATE..."). A period inside parentheses never ends the list; a period
    followed by more comma-separated items is read as a separator. Dropping those items would hide allergens.
    """
    depth, separators = 0, set()
    for i, ch in enumerate(body):
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth = max(depth - 1, 0)
        elif ch == "." and depth == 0 and (i + 1 == len(body) or body[i + 1].isspace()):
            following = re.split(r"\.(?:\s|$)", body[i + 1:], maxsplit=1)[0]
            if "," in following or ";" in following:
                separators.add(i)
            else:
                return i, separators
    return len(body), separators


def normalize_keep_len(text: str) -> str:
    """Accent-strip and lowercase one character at a time, keeping offsets aligned."""
    out = []
    for ch in text:
        base = "".join(c for c in unicodedata.normalize("NFKD", ch) if not unicodedata.combining(c))
        out.append((base or ch)[0].lower())
    return "".join(out)


def groups_in(text: str, matcher: Matcher) -> set[str]:
    groups = set()
    for t in matcher.find(text):
        groups |= t.allergens & ALLERGEN_GROUPS
    return groups


def parse_statements(text: str, matcher: Matcher) -> Statements:
    st = Statements(raw=text.strip())
    norm = normalize(text)
    if GLUTEN_FREE.search(norm):
        st.gluten = "free"
    elif GLUTEN_CONTAINS.search(norm):
        st.gluten = "contains"
    if LACTOSE_FREE.search(norm):
        st.lactose = "free"
    elif LACTOSE_CONTAINS.search(norm):
        st.lactose = "contains"
    st.vegan_claim = bool(VEGAN_CLAIM.search(norm))
    st.vegetarian_claim = bool(VEGETARIAN_CLAIM.search(norm))

    # Remove the gluten/lactose claims so "não contém glúten" is not read as an allergen.
    norm = GLUTEN_FREE.sub(" ", LACTOSE_FREE.sub(" ", LACTOSE_CONTAINS.sub(" ", norm)))
    for sentence in re.split(r"[.!]", norm):
        may = MAY_CONTAIN.search(sentence)
        head, tail = (sentence[:may.start()], sentence[may.end():]) if may else (sentence, "")
        if tail:
            st.allergen_statement_found = True
            st.may_contain |= groups_in(tail, matcher)
        has = CONTAINS.search(head)
        if has:
            if re.search(r"\b(alergicos|alergenos|allergens|allergenes|allergene|contains|contiene|contient|enthalt|"
                         r"bevat|derivados)\b", head):
                st.allergen_statement_found = True
            st.contains |= groups_in(head[has.end():], matcher)
    return st


# ---------------------------------------------------------------- checking

def normalize_avoid(avoid: list[str]) -> list[str]:
    out = []
    for a in avoid:
        a = normalize(a).replace("-", " ")
        a = AVOID_ALIASES.get(a, a.replace(" ", "_"))
        if a not in out:
            out.append(a)
    return out


# Symptoms of an allergic reaction described as happening now (PT, EN, ES). Checked before any analysis.
URGENT = re.compile(
    r"\b(lips?|tongue|throat|face|eyes?|labios?|lingua|garganta|rosto|boca|olhos?|lengua|cara)\b[^.]{0,30}"
    r"\b(swelling|swollen|closing|tight|tingling|inchad[oa]s?|inchando|fechando|apertad[oa]|coca|cocando|"
    r"formigando|hinchad[oa]s?|cerrando)\b"
    r"|\b(can ?not|can't|cant|hard to|trouble|difficulty) breath(e|ing)\b"
    r"|\b(nao consigo|dificuldade (para|de)|falta de) respira|\bfalta de ar\b|\bme cuesta respirar\b|\bno puedo respirar\b"
    r"|\b(hives|anaphyla\w*|anafila\w*|urticaria)\b.{0,40}\b(now|right now|agora|ahora|started|comecou|empezo)\b"
    r"|\b(i ate|i just ate|comi|acabei de comer|acabo de comer)\b.{0,80}\b(swell|inch|hinch|itch|coc|vomit|"
    r"breath|respir)")
OAT = re.compile(r"\b(oat|oats|aveia|avena|avoine|hafer|haver)\b")


def oats_only_gluten(term: Term, market: str) -> bool:
    """In the US oats are not a gluten-containing grain (21 CFR 101.91); in Brazil (Anvisa) and the EU
    (Regulation 1169/2011 Annex II) they are. Oats are still often cross-contaminated."""
    return market.upper() == "US" and term.gluten == "red" and bool(OAT.search(term.term)) \
        and not re.search(r"\b(wheat|barley|rye|trigo|cevada|centeio|malt|malte)\b", term.term)


def status_for(term: Term, avoid: str, lactose_free_with_lactase: bool, market: str = "BR") -> tuple[str, str]:
    """Status of one matched term for one restriction, plus a short reason."""
    if avoid == "gluten" and oats_only_gluten(term, market):
        return "yellow", ("Oats are not a gluten grain under US rules, but are often cross-contaminated; "
                          "look for certified gluten-free oats")
    if avoid == "lactose":
        level = term.lactose or "green"
        if level != "green" and lactose_free_with_lactase and "milk" in term.allergens:
            return "green", "lactose-free claim and lactase listed"
        return level, term.note if level != "green" else ""
    if avoid == "vegan":
        if term.origin == "animal":
            return "red", f"animal-derived ({term.animal_type})"
        if term.origin in ("either", "unknown"):
            return "yellow", f"can be either: {term.note}".rstrip(": ")
        return "green", ""
    if avoid == "vegetarian":
        if term.origin == "animal" and term.animal_type in VEGETARIAN_RED:
            return "red", f"animal-derived ({term.animal_type})"
        if term.origin == "animal" and term.animal_type in VEGETARIAN_YELLOW:
            return "yellow", term.note
        if term.origin in ("either", "unknown"):
            return "yellow", f"can be either: {term.note}".rstrip(": ")
        return "green", ""
    if avoid == "gluten" and term.gluten:
        return term.gluten, term.note if term.gluten != "green" else ""
    if avoid == "milk" and term.lactose == "yellow" and "milk" not in term.allergens:
        return "yellow", term.note
    if avoid in term.allergens:
        return "red", f"contains {avoid}"
    if avoid in term.may_allergens:
        return "yellow", f"source not stated; may contain {avoid}"
    return "green", ""


def check_label(label_text: str, avoid: list[str], strict: bool = False, market: str = "BR",
                matcher: Matcher | None = None) -> dict:
    """Classify a transcribed label or recipe against a profile and cross-check its statements."""
    if URGENT.search(normalize(label_text)):
        # US-08: symptoms happening now come before any label analysis.
        return {"rules_version": RULES_VERSION, "verdict": "urgent",
                "action": "Symptoms of a possible allergic reaction were described. Tell the user to seek emergency "
                          "medical help now (Brazil SAMU 192, US 911, EU 112) and to use their adrenaline "
                          "auto-injector if they have one. Do not analyse the label.",
                "escalate_to_human_review": False}
    matcher = matcher or Matcher()
    avoid = normalize_avoid(avoid)
    items, st = parse_label(label_text, matcher)
    if not items:
        return {"rules_version": RULES_VERSION, "verdict": "insufficient",
                "reason": "No ingredient list found. Ask for a photo of the ingredient panel or the list."}

    matched = [(item, matcher.find(item)) for item in items]
    terms = [t for _, ts in matched for t in ts]
    has_lactase = any(t.term == "lactase" for t in terms)
    lactose_free_with_lactase = st.lactose == "free" and has_lactase

    ingredients, findings = [], []
    for item, ts in matched:
        entry = {"text": item, "matched_terms": [t.term for t in ts],
                 "origin": "unknown" if not ts else _merge_origin(ts), "status": {}, "notes": []}
        for t in ts:
            if t.note and t.note not in entry["notes"]:
                entry["notes"].append(t.note)
        for a in avoid:
            if not ts:
                level, why = "yellow", "not in the ingredient database; check it"
            else:
                pairs = [status_for(t, a, lactose_free_with_lactase, market) for t in ts]
                level = worst(*(p[0] for p in pairs))
                why = "; ".join(sorted({p[1] for p in pairs if p[0] == level and p[1]}))
            if strict and level == "yellow" and a not in DIETS:
                level, why = "red", f"STRICT mode: {why}"
            entry["status"][a] = level
            if level != "green":
                findings.append({"ingredient": item, "restriction": a, "level": level, "why": why})
        ingredients.append(entry)

    findings += _statement_findings(st, avoid, strict)
    mismatches = _cross_check(st, terms, has_lactase, market)

    verdict = worst(*(f["level"] for f in findings)) if findings else "green"
    if mismatches:
        verdict = worst(verdict, "red" if strict else "yellow")
    notes = []
    if market.upper() == "BR" and st.gluten == "not found" and ("gluten" in avoid or not avoid):
        notes.append("No CONTÉM GLÚTEN / NÃO CONTÉM GLÚTEN statement found (required in Brazil by Lei 10.674/2003).")
    if any(t.allergens - {"gluten"} for t in terms) and not st.allergen_statement_found:
        notes.append("No allergen statement found in the text provided.")
    if set(avoid) & DIETS:
        notes.append("Processing aids and cross-contact are usually not visible on a label.")
    not_required = sorted({g for t in terms for g in t.allergens & ALLERGEN_GROUPS}
                          - MARKET_ALLERGENS.get(market.upper(), ALLERGEN_GROUPS))
    if not_required:
        notes.append(f"Contains {', '.join(not_required)}: an allergen elsewhere, but not one this market "
                     f"({market.upper()}) requires in the allergen statement.")
    unknown = sum(1 for _, ts in matched if not ts)
    return {
        "rules_version": RULES_VERSION,
        "data_version": f"{matcher.data_version} terms",
        "data_license": "Open Food Facts terms: ODbL 1.0, © Open Food Facts contributors",
        "market": market.upper(),
        "mode": "STRICT" if strict else ("DIET" if set(avoid) <= DIETS and avoid else "INFORMATIVE"),
        "profile": avoid,
        "verdict": verdict,
        "escalate_to_human_review": bool(mismatches) or (strict and verdict != "green"),
        "coverage": f"{len(items) - unknown}/{len(items)} ingredients found in the database",
        "ingredients": ingredients,
        "statements": {"allergen_statement_found": st.allergen_statement_found,
                       "contains": sorted(st.contains), "may_contain": sorted(st.may_contain),
                       "gluten": st.gluten, "lactose": st.lactose,
                       "vegan_claim": st.vegan_claim, "vegetarian_claim": st.vegetarian_claim},
        "findings": findings,
        "mismatches": mismatches,
        "notes": notes,
        "compliance": compliance_checklist(st, terms, mismatches, market),
        "wording": wording_for(verdict, avoid),
    }


def wording_for(verdict: str, avoid: list[str]) -> str:
    """US-07: the sentence to use instead of "safe". A green verdict only means nothing was found in the text."""
    what = ", ".join(avoid) or "a problem"
    if verdict == "green":
        return (f'Say "I did not find {what} in the text I could read." Never say "safe", "seguro", "free of" '
                'or "vegan for sure": processing aids and cross-contact are not on labels.')
    return 'Never say "safe" or "seguro". Explain each red and yellow item and what would settle it.'


def compliance_checklist(st: Statements, terms: list[Term], mismatches: list[dict], market: str) -> list[dict]:
    """D-07: first-pass label compliance checks for the Analyst workflow, per market.

    Each check is pass / fail / review (a person must look) / n/a, with its legal basis. Text alone cannot prove
    compliance: format (bold, 2 mm letters), quantities and processing aids are outside what the engine reads.
    """
    market = market.upper()
    required = MARKET_ALLERGENS.get(market, ALLERGEN_GROUPS)
    listed = {g for t in terms for g in t.allergens if g in required
              and not (g == "gluten" and oats_only_gluten(t, market))}
    rules = {m["rule"] for m in mismatches}
    out = []

    def add(check, status, basis, detail=""):
        out.append({"check": check, "status": status, "basis": basis, "detail": detail})

    basis = {"BR": "RDC 26/2015 (in RDC 727/2022)", "US": "FALCPA 2004, FASTER Act 2021",
             "EU": "Regulation (EU) 1169/2011, Art. 21 and Annex II"}.get(market, "")
    if not listed:
        add("Allergen declaration", "n/a", basis, "No allergen of this market found in the ingredients read.")
    elif market == "EU":
        add("Allergen declaration", "review", basis,
            f"Ingredients include {', '.join(sorted(listed))}. In the EU they must be emphasised in the list "
            "(for example in bold); emphasis cannot be read from text.")
    elif not st.allergen_statement_found:
        add("Allergen declaration", "fail" if market == "BR" else "review", basis,
            f"Ingredients include {', '.join(sorted(listed))}, but no allergen statement was found."
            + (" In the US the source may instead appear in parentheses after the ingredient." if market == "US" else ""))
    elif "XC2" in rules:
        add("Allergen declaration", "fail", basis, "The statement leaves out an allergen listed in the ingredients.")
    else:
        add("Allergen declaration", "pass", basis, f"Declares {', '.join(sorted(listed))}.")

    if market == "BR":
        add("Gluten statement", "pass" if st.gluten != "not found" else "fail", "Lei 10.674/2003",
            "" if st.gluten != "not found" else 'Neither "CONTÉM GLÚTEN" nor "NÃO CONTÉM GLÚTEN" was found.')
        dairy = sorted({t.term for t in terms if t.lactose == "red"})
        if st.lactose == "free":
            add("Lactose-free claim", "fail" if "XC3" in rules else "review", "RDC 135/2017 and 136/2017",
                "Claim with milk listed and no lactase." if "XC3" in rules
                else "Claim allowed up to 100 mg of lactose per 100 g or mL: confirm with a lab result.")
        elif dairy:
            add('"Contém lactose" statement', "pass" if st.lactose == "contains" else "review",
                "RDC 135/2017 and 136/2017", "" if st.lactose == "contains" else
                f"{', '.join(dairy)} listed: above 100 mg of lactose per 100 g or mL the label must say "
                '"CONTÉM LACTOSE". The amount cannot be checked from text.')
    if st.gluten == "free":
        law = {"BR": "Lei 10.674/2003", "US": "21 CFR 101.91", "EU": "Regulation (EU) 828/2014"}.get(market, "")
        add("Gluten-free claim", "fail" if "XC1" in rules else "pass", law,
            "A gluten source is listed or may be present." if "XC1" in rules else "")
    if st.vegan_claim:
        add("Vegan claim", "fail" if "XC4" in rules else "review", "No legal definition in BR or the US",
            "Animal-derived items listed." if "XC4" in rules else "No animal-derived item found; claim not verified.")
    return out


def _merge_origin(ts: list[Term]) -> str:
    origins = {t.origin for t in ts}
    for o in ("animal", "either", "unknown"):
        if o in origins:
            return o
    return sorted(origins)[0]


def _statement_findings(st: Statements, avoid: list[str], strict: bool) -> list[dict]:
    out = []
    for a in avoid:
        groups = {"lactose": {"milk"}, "vegan": {"milk", "egg", "fish", "crustacean", "mollusc"},
                  "vegetarian": {"fish", "crustacean", "mollusc"}}.get(a, {a})
        # A zero-lactose claim settles lactose for the milk declaration (XC3 catches it when lactase is missing).
        if st.contains & groups and not (a == "lactose" and st.lactose == "free"):
            out.append({"ingredient": "allergen statement", "restriction": a, "level": "red",
                        "why": f"label declares: contains {', '.join(sorted(st.contains & groups))}"})
        if st.may_contain & groups:
            level = "red" if strict and a not in DIETS else "yellow"
            out.append({"ingredient": "may-contain statement", "restriction": a, "level": level,
                        "why": f"possible traces: {', '.join(sorted(st.may_contain & groups))}"})
    return out


def _cross_check(st: Statements, terms: list[Term], has_lactase: bool, market: str = "BR") -> list[dict]:
    out = []
    required = MARKET_ALLERGENS.get(market.upper(), ALLERGEN_GROUPS)
    gluten_terms = sorted({t.term for t in terms if t.gluten == "red" and not oats_only_gluten(t, market)})
    if st.gluten == "free" and (gluten_terms or "gluten" in st.contains | st.may_contain):
        out.append({"rule": "XC1", "issue": "Label says NÃO CONTÉM GLÚTEN / gluten free, but lists or may contain "
                    f"a gluten source: {', '.join(gluten_terms) or 'see allergen statement'}."})
    if st.allergen_statement_found:
        listed = {g for t in terms for g in t.allergens if g in required
                  and not (g == "gluten" and oats_only_gluten(t, market))}
        missing = sorted(listed - st.contains - st.may_contain)
        if missing:
            out.append({"rule": "XC2", "issue": f"Ingredients include {', '.join(missing)}, "
                        "but the allergen statement does not declare it."})
    if st.lactose == "free" and not has_lactase:
        dairy = sorted({t.term for t in terms if t.lactose == "red"})
        if dairy:
            out.append({"rule": "XC3", "issue": f"Zero-lactose claim, but {', '.join(dairy)} listed and no lactase."})
    if st.vegan_claim:
        animal = sorted({t.term for t in terms if t.origin == "animal"} |
                        (st.contains & {"milk", "egg", "fish", "crustacean", "mollusc"}))
        if animal:
            out.append({"rule": "XC4", "issue": f"Vegan claim, but animal-derived items found: {', '.join(animal)}."})
    return out


def lookup(name: str, con: sqlite3.Connection | None = None) -> list[dict]:
    """Exact and partial matches for one ingredient name, straight from SQL."""
    key = normalize(name)
    with closing(connect()) if con is None else nullcontext(con) as c:
        rows = c.execute(
            "SELECT * FROM ingredient WHERE term = ? OR term LIKE ? OR ? LIKE '%' || term || '%' "
            "ORDER BY term = ? DESC, length(term) DESC LIMIT 10", (key, f"%{key}%", key, key)).fetchall()
    return [dict(r) for r in rows]
