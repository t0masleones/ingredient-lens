def build_db(csv_paths: tuple[Path, ...] = (CSV_PATH, OFF_PATH), db_path: Path = DB_PATH) -> Path:
    """(Re)build the SQLite ingredient master from the versioned CSVs. Earlier files win on duplicate terms."""
    db_path.unlink(missing_ok=True)
    con = sqlite3.connect(db_path)
    con.execute("""CREATE TABLE ingredient (
        term TEXT PRIMARY KEY, lang TEXT, lactose TEXT, gluten TEXT, allergens TEXT,
        may_allergens TEXT, origin TEXT, animal_type TEXT, note TEXT, source TEXT)""")
    for i, path in enumerate(p for p in csv_paths if p.exists()):
        with open(path, encoding="utf-8", newline="") as f:
            rows = [{**r, "term": normalize(r["term"])} for r in csv.DictReader(f)]
        # The curated file must not contain duplicates; generated files only fill gaps.
        con.executemany(f"""INSERT {'OR IGNORE ' if i else ''}INTO ingredient VALUES (:term, :lang, :lactose,
            :gluten, :allergens, :may_allergens, :origin, :animal_type, :note, :source)""", rows)
    con.commit()
    con.close()
    return db_path


def connect() -> sqlite3.Connection:
    newest = max(p.stat().st_mtime for p in (CSV_PATH, OFF_PATH) if p.exists())
    if not DB_PATH.exists() or DB_PATH.stat().st_mtime < newest:
        build_db()
    con = sqlite3.connect(DB_PATH)
    con.row_factory = sqlite3.Row
    return con


@dataclass
class Term:
    term: str
    lactose: str
    gluten: str
    allergens: set[str]
    may_allergens: set[str]
    origin: str
    animal_type: str
    note: str
    source: str

    @classmethod
    def from_row(cls, r: sqlite3.Row) -> "Term":
        split = lambda s: {x for x in (s or "").split(";") if x}
        allergens = split(r["allergens"])
        if r["gluten"] == "red":
            allergens.add("gluten")
        return cls(r["term"], r["lactose"] or "", r["gluten"] or "", allergens, split(r["may_allergens"]),
                   r["origin"], r["animal_type"] or "", r["note"] or "", r["source"])


class Matcher:
    """Longest-match term finder over normalized text (allows a plural s/es)."""

    def __init__(self, con: sqlite3.Connection | None = None, sources: str = "all"):
        # Terms are loaded into memory; a connection opened here is closed so the .db file stays rebuildable.
        where = "" if sources == "all" else f" WHERE source NOT LIKE '{OFF_SOURCE}%'"
        with closing(connect()) if con is None else nullcontext(con) as c:
            self.terms = {r["term"]: Term.from_row(r) for r in c.execute(f"SELECT * FROM ingredient{where}")}
        alternation = "|".join(re.escape(t) for t in sorted(self.terms, key=len, reverse=True))
        # Plural and German case endings: "ovos", "nozes", "Haselnüssen".
        self.pattern = re.compile(rf"\b({alternation})(?:s|es|n|en)?\b")
        imported = sum(t.source.startswith(OFF_SOURCE) for t in self.terms.values())
        self.data_version = f"{len(self.terms) - imported} curated + {imported} Open Food Facts"

    def find(self, text: str) -> list[Term]:
        return [self.terms[m.group(1)] for m in self.pattern.finditer(normalize(text))]


